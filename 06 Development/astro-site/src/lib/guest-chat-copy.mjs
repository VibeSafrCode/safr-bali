Object.freeze(copy);
export function guestChatLocale(locale) {
 const canonical=locale==='zh-cn'?'zh-Hans':locale;
 if (!GUEST_CHAT_LOCALES.includes(canonical)) throw new Error('Unsupported guest chat locale');
 return canonical;
}
export function guestChatText(key, locale) {
 const values = copy[guestChatLocale(locale)];
 if (!Object.hasOwn(values, key)) throw new Error('Unknown guest chat caption');
 return values[key];
}

